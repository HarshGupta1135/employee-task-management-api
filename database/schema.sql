-- =====================================================================
-- Employee Task Management API - PostgreSQL schema
-- =====================================================================
-- You normally do NOT need to run this file: the application creates the
-- schema automatically on start-up with Flyway
-- (src/main/resources/db/migration/V1__init_schema.sql, identical DDL).
--
-- Manual setup (optional):
--   createdb -U postgres taskdb
--   psql -U postgres -d taskdb -f database/schema.sql
-- The application detects the existing tables and baselines Flyway at
-- version 1 (spring.flyway.baseline-on-migrate=true).
--
-- Demo users and tasks are inserted by the application on first start
-- (DataSeeder). A full dump including demo data is in taskdb-dump.sql.
-- =====================================================================

-- Employees. Passwords are stored as BCrypt hashes, emails in lower case.
CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR(100)             NOT NULL,
    email       VARCHAR(150)             NOT NULL,
    password    VARCHAR(100)             NOT NULL,
    role        VARCHAR(20)              NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'USER'))
);

-- Tasks. "priority" holds a numeric level (1 = LOW, 2 = MEDIUM, 3 = HIGH, 4 = CRITICAL)
-- so that ORDER BY priority follows business order; "version" is used for optimistic locking.
CREATE TABLE tasks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(150)             NOT NULL,
    description  VARCHAR(2000),
    status       VARCHAR(20)              NOT NULL,
    priority     INTEGER                  NOT NULL,
    due_date     DATE,
    assignee_id  BIGINT,
    created_by   BIGINT                   NOT NULL,
    version      BIGINT                   NOT NULL DEFAULT 0,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_tasks_assignee FOREIGN KEY (assignee_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_tasks_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT ck_tasks_status CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE')),
    CONSTRAINT ck_tasks_priority CHECK (priority BETWEEN 1 AND 4)
);

-- Indexes for the access-control filter (assignee / creator) and the common list filters and sorts.
CREATE INDEX idx_tasks_assignee ON tasks (assignee_id);
CREATE INDEX idx_tasks_created_by ON tasks (created_by);
CREATE INDEX idx_tasks_status ON tasks (status);
CREATE INDEX idx_tasks_due_date ON tasks (due_date);
